"""Draws the SafeWalk app icon for both platforms from one geometry.

The mark is the logo (LogoMark in the apps): a stepped route from A to B with a dot at each end, ink on coral. Coordinates are in the 108-unit adaptive-icon grid; the middle 72 units are what a
launcher shows, and the iOS / Play Store PNGs are that visible square.

    python3 android/tools/make_icons.py      # from the repo root; needs Pillow

Writes:
    android/app/src/main/res/drawable/ic_launcher_foreground.xml
    android/app/src/main/res/drawable/ic_launcher_monochrome.xml
    ios/SafeWalk/Resources/Assets.xcassets/AppIcon.appiconset/AppIcon-1024.png
    docs/store/icon-512.png   (Google Play listing icon)
"""
import pathlib

from PIL import Image, ImageDraw

ROOT = pathlib.Path(__file__).resolve().parents[2]
CORAL, INK = "#FF8A8A", "#231C1E"

A, B = (36.0, 72.0), (72.0, 36.0)
STEPS = [A, (36.0, 54.0), (54.0, 54.0), (54.0, 36.0), B]
ROUTE_W, DOT_R = 7.0, 6.5


def fmt(v):
    return f"{v:.2f}".rstrip("0").rstrip(".")


def circle_path(c, r):
    x, y = c
    return f"M{fmt(x - r)},{fmt(y)}a{fmt(r)},{fmt(r)} 0,1 1,{fmt(2 * r)},0a{fmt(r)},{fmt(r)} 0,1 1,{fmt(-2 * r)},0Z"


def vector(ink):
    route = "M" + " L".join(f"{fmt(x)},{fmt(y)}" for x, y in STEPS)
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by android/tools/make_icons.py: the stepped route from A to B, as in the in-app logo. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <path android:pathData="{route}" android:strokeColor="{ink}" android:strokeWidth="{fmt(ROUTE_W)}"
        android:strokeLineCap="round" android:strokeLineJoin="round" android:fillColor="#00000000" />
    <path android:pathData="{circle_path(A, DOT_R)}" android:fillColor="{ink}" />
    <path android:pathData="{circle_path(B, DOT_R)}" android:fillColor="{ink}" />
</vector>
"""


def png(size, path):
    ss = 4                      # draw large, then downsample for smooth edges
    px = size * ss
    scale = px / 72.0           # visible square is units 18..90
    tr = lambda p: ((p[0] - 18) * scale, (p[1] - 18) * scale)
    img = Image.new("RGB", (px, px), CORAL)
    d = ImageDraw.Draw(img)

    def seg(a, b, w, color):
        a, b = tr(a), tr(b)
        d.line([a, b], fill=color, width=round(w * scale))
        r = w * scale / 2
        for x, y in (a, b):
            d.ellipse([x - r, y - r, x + r, y + r], fill=color)

    for a, b in zip(STEPS, STEPS[1:]):
        seg(a, b, ROUTE_W, INK)
    for c in (A, B):
        x, y = tr(c)
        r = DOT_R * scale
        d.ellipse([x - r, y - r, x + r, y + r], fill=INK)
    img = img.resize((size, size), Image.LANCZOS)
    path.parent.mkdir(parents=True, exist_ok=True)
    img.save(path, optimize=True)


if __name__ == "__main__":
    res = ROOT / "android/app/src/main/res/drawable"
    (res / "ic_launcher_foreground.xml").write_text(vector(INK))
    # themed icons (Android 13+) tint this layer by its alpha alone
    (res / "ic_launcher_monochrome.xml").write_text(vector("#FFFFFFFF"))
    png(1024, ROOT / "ios/SafeWalk/Resources/Assets.xcassets/AppIcon.appiconset/AppIcon-1024.png")
    png(512, ROOT / "docs/store/icon-512.png")
    print("icons written")
